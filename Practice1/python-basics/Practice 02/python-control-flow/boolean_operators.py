# Example 1: AND operator
x = 5
print(x > 0 and x < 10)


# Example 2: AND operator with False
age = 15
print(age >= 18 and age <= 30)


# Example 3: OR operator
age = 15
print(age < 18 or age > 60)


# Example 4: NOT operator
x = 5
print(not x > 10)


# Example 5: Combining Boolean operators
age = 20
has_ticket = True

print(age >= 18 and has_ticket)