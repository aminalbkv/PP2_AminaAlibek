# Example 1: Comparing values
print(10 > 9)
print(10 == 9)
print(10 < 9)


# Example 2: Boolean with if statement
a = 200
b = 33

if b > a:
    print("b is greater than a")
else:
    print("b is not greater than a")


# Example 3: Evaluate values
print(bool("Hello"))
print(bool(15))


# Example 4: True and False values
print(bool("abc"))
print(bool(123))
print(bool(""))
print(bool(0))


