# 1. Convert to integer
x = int(5.9)
y = int("10")

print(x)
print(y)
print(type(x))
print(type(y))


# 2. Convert to float
a = float(5)
b = float("3.5")

print(a)
print(b)
print(type(a))
print(type(b))


# 3. Convert to string
age = 18
height = 170.5

age_text = str(age)
height_text = str(height)

print(age_text)
print(height_text)

print(type(age_text))
print(type(height_text))